import type { Metadata } from "next";
import { site } from "@/content/site";
import { absoluteUrl } from "./siteUrl";

type SeoInput = {
  /** Page title without the brand; the root template adds " | gYOU". */
  title: string;
  description: string;
  /** Route path, e.g. "/services". Used for the canonical URL. */
  path: string;
  /** Use the title as-is (no template), e.g. the homepage. */
  absoluteTitle?: boolean;
  /** Short label shown above the title on the generated OG image. */
  ogEyebrow?: string;
  type?: "website" | "article";
  publishedTime?: string;
  modifiedTime?: string;
  noindex?: boolean;
};

/** Open Graph image generated by app/og/route.tsx in the Editorial Luxe style. */
export function ogImageUrl(title: string, eyebrow?: string): string {
  // The image already shows the wordmark, so drop a trailing " | gYOU".
  const params = new URLSearchParams({ title: title.replace(` | ${site.name}`, "") });
  if (eyebrow) params.set("eyebrow", eyebrow);
  return `/og?${params.toString()}`;
}

/**
 * Per-route metadata (Phase 8): unique title and description, canonical URL,
 * Open Graph card. Indexing itself is decided in the root layout
 * (only the production site is indexable).
 */
export function buildMetadata(input: SeoInput): Metadata {
  const url = absoluteUrl(input.path);
  const image = ogImageUrl(input.title, input.ogEyebrow);
  return {
    title: input.absoluteTitle ? { absolute: input.title } : input.title,
    description: input.description,
    alternates: { canonical: url },
    openGraph: {
      type: input.type ?? "website",
      url,
      siteName: site.name,
      locale: "en_IN",
      title: input.title,
      description: input.description,
      images: [{ url: image, width: 1200, height: 630, alt: input.title }],
      ...(input.publishedTime ? { publishedTime: input.publishedTime } : {}),
      ...(input.modifiedTime ? { modifiedTime: input.modifiedTime } : {}),
    },
    ...(input.noindex ? { robots: { index: false, follow: false } } : {}),
  };
}
